/** True when a URL slug names one of the three workbooks. */
export function isWorkbookSlug(slug: string): slug is WorkbookSlug {
  return (WORKBOOK_SLUGS as readonly string[]).includes(slug);
}

export function getWorkbook(slug: string): Workbook | undefined {
  return workbooks.find((workbook) => workbook.slug === slug);
}

/** Total reading time across a workbook's modules, in minutes. */
export function workbookMinutes(workbook: Workbook): number {
  return workbook.modules.reduce((sum, module) => sum + module.minutes, 0);
}
